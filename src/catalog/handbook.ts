import { TABLES } from './ruleTables.ts';
import type { BlockKey } from '../types.ts';

export type Stage = 'basic' | 'extended';

export interface ClauseOption { label: string; score: number }

export interface HandbookClause {
  /** 稳定 id：de-6 / zhi-20 …… 记录会存这个值，改名不影响归属 */
  id: string;
  block: BlockKey;
  /** 手册条号，如 6 表示"第六条" */
  no: number;
  stage: Stage;
  /** 一句话短标题，列表里显示 */
  title: string;
  /** 手册原文（完整，不简化） */
  text: string;
  /** 该条上限分（手册写了才填） */
  cap?: number;
  /** 计分口径的极简说明，如 每次10分 */
  unit?: string;
  /** 手册给定的离散分值预设（等级 / 奖项×级别 / 荣誉级别） */
  options?: ClauseOption[];
  /** 章导语：只读，不可填写 */
  intro?: boolean;
}

/** 把分值表展开成"奖项 · 级别"预设（第二十条 / 第二十七条 / 第三十四条用） */
function tableOptions(id: string): ClauseOption[] {
  const t = TABLES.find((x) => x.id === id);
  if (!t) return [];
  const out: ClauseOption[] = [];
  for (const r of t.rows) {
    t.cols.forEach((c, i) => {
      const v = r.scores[i];
      if (typeof v === 'number') out.push({ label: r.prize + ' · ' + c, score: v });
    });
  }
  return out;
}

const lv = (pairs: [string, number][]): ClauseOption[] => pairs.map(([label, score]) => ({ label, score }));

