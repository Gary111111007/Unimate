/** 章导语（只读抬头），按板块取 */
export function chapterIntro(block: BlockKey): HandbookClause | undefined {
  return HANDBOOK.find((c) => c.block === block && c.intro);
}
/** 可填写条款 */
export const FILLABLE = HANDBOOK.filter((c) => !c.intro);
export function clausesOf(block: BlockKey, stage?: Stage): HandbookClause[] {
  return FILLABLE.filter((c) => c.block === block && (!stage || c.stage === stage));
}
export function clauseById(id: string | undefined): HandbookClause | undefined {
  return id ? HANDBOOK.find((c) => c.id === id) : undefined;
}
